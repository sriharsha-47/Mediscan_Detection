"""Part 1, task 3: leakage-free replacement split. Locked test set + 5 stratified, patient-grouped folds."""
import numpy as np, pandas as pd
from sklearn.model_selection import StratifiedGroupKFold
from common import *


def main():
    set_seed(SEED)
    df = load_manifest()
    n = len(df)
    # groups = patient id, merged with near-duplicate clusters (pHash<=3) so near-copies never straddle a split
    parent = list(range(n))
    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]; a = parent[a]
        return a
    def union(a, b): parent[find(a)] = find(b)
    first = {}
    for i, p in enumerate(df.patient.values):
        if p in first: union(i, first[p])
        else: first[p] = i
    D = hamming_matrix(df.phash.tolist())
    for a, b in np.argwhere(np.triu(D <= 3, 1)): union(int(a), int(b))
    df["group"] = [find(i) for i in range(n)]

    y, g = df.label.values, df.group.values
    outer = StratifiedGroupKFold(n_splits=7, shuffle=True, random_state=SEED)       # ~14% locked test
    pool_idx, test_idx = next(iter(outer.split(np.zeros(n), y, g)))
    df["split"] = "pool"; df.loc[test_idx, "split"] = "test"; df["fold"] = -1
    inner = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=SEED)
    for f, (_, vi) in enumerate(inner.split(np.zeros(len(pool_idx)), y[pool_idx], g[pool_idx])):
        df.loc[pool_idx[vi], "fold"] = f
    assert not set(g[pool_idx]) & set(g[test_idx]), "group leakage between pool and test!"
    for f in range(5):
        a = set(g[(df.fold != f) & (df.split == "pool")]); b = set(g[df.fold == f]); assert not a & b
    df.to_csv(RESULTS / "splits.csv", index=False)

    tab = pd.crosstab([df.split, df.fold], df.label_name); tab["pct_pneumonia"] = (100 * tab.PNEUMONIA / tab.sum(1)).round(1)
    moved = (df.orig_split != df.split.replace({"pool": "train"})).sum()
    txt = f"""# Split design (auto-generated by split.py)
{tab.to_markdown()}

Groups = {df.group.nunique()} (patient IDs merged with near-duplicate clusters). No group appears in two splits (asserted).

## Why a locked test set + k-fold, and not one alone
* **Locked patient-grouped hold-out test (~14%)**: touched only for final reporting; gives one unbiased number.
* **5 stratified, patient-grouped folds on the remaining pool**: fold 0 acts as the validation set for model selection;
  all five give mean ± std for Part 2.
* **Rejected: a single train/val/test split only** - with ~800 validation images the estimate still carries sampling noise
  (CI width roughly ±3 pp at 90% accuracy), and every tuning decision overfits that one slice.
* **Rejected: k-fold only (no locked test)** - every image gets used for tuning at some point, so the reported CV score
  is optimistically biased by hyper-parameter and threshold selection.
* **Patient grouping** is essential: several X-rays per child exist (person123_bacteria_1/2/3), so image-level splitting
  lets the model recognise the child instead of the disease.
* Original Kaggle split pooled and re-split by patient: {moved} of {n} images changed split.
"""
    open(RESULTS / "split_summary.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
