"""Part 2, task 1: class weights vs threshold moving; cost-optimal threshold at camp prevalence; ROC/PR with the chosen point."""
import argparse, json
import numpy as np, pandas as pd, torch
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.stats import spearmanr
from sklearn.metrics import roc_curve, precision_recall_curve
from common import *


def camp_stats(tpr, fpr, prev=CAMP_PREV):
    tp, fn, fp, tn = prev * tpr, prev * (1 - tpr), (1 - prev) * fpr, (1 - prev) * (1 - fpr)
    return dict(ppv=tp / (tp + fp) if tp + fp else float("nan"), npv=tn / (tn + fn) if tn + fn else float("nan"),
                cost_per_child=C_FN * fn + C_FP * fp, accuracy=tp + tn)


def op_at_sens(y, p, target=0.95):
    fpr, tpr, thr = roc_curve(y, p); i = np.where(tpr >= target)[0][0]; return float(thr[i])


def rel_dist(a, b):
    sa, sb = torch.load(a, map_location="cpu", weights_only=False)["state"], torch.load(b, map_location="cpu", weights_only=False)["state"]
    num = sum(((sa[k].float() - sb[k].float()) ** 2).sum() for k in sa if sa[k].dtype.is_floating_point)
    den = sum((sa[k].float() ** 2).sum() for k in sa if sa[k].dtype.is_floating_point)
    return float((num / den).sqrt())


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--tag", default="arogyanet_tuned"); a = ap.parse_args()
    set_seed(SEED); df = load_splits(); y = df.label.values; cw = a.tag + "_cw"; out = []; P = out.append
    P("# Imbalance, threshold and cost (auto-generated by threshold_cost.py)\n")
    # ---------- A. class weights change the MODEL, threshold changes only the DECISION
    rows = []
    for s in sorted(set(run_seeds(a.tag)) & set(run_seeds(cw))):
        ju, nu = load_run(a.tag, s); jw, nw = load_run(cw, s); yv, yt = y[nu["val_idx"]], y[nu["test_idx"]]
        thr_u, thr_w = op_at_sens(yv, nu["val_prob"]), op_at_sens(yv, nw["val_prob"])
        mu, mw = compute_metrics(yt, nu["test_prob"], thr_u), compute_metrics(yt, nw["test_prob"], thr_w)
        rows.append(dict(seed=s, weight_rel_L2_distance=rel_dist(MODELS / f"{a.tag}_s{s}.pt", MODELS / f"{cw}_s{s}.pt"),
                         val_AUC_plain=ju["val"]["roc_auc"], val_AUC_weighted=jw["val"]["roc_auc"],
                         mean_prob_plain=float(nu["val_prob"].mean()), mean_prob_weighted=float(nw["val_prob"].mean()),
                         spearman_val_probs=float(spearmanr(nu["val_prob"], nw["val_prob"])[0]),
                         test_spec_at_95sens_threshold_moved=mu["specificity"], test_sens_at_95=mu["recall"],
                         test_spec_at_95sens_weighted=mw["specificity"], test_sens_w=mw["recall"]))
    if rows:
        A = pd.DataFrame(rows).round(4); A.to_csv(RESULTS / "weights_vs_threshold.csv", index=False)
        P("## A. Training-side treatment (class weights) vs threshold moving\n" + A.T.to_markdown() +
          "\n\nRead: class weights give a *different network* (non-zero weight distance, different AUC and different probability scale / ranking: "
          "Spearman < 1). Threshold moving leaves the network and its AUC untouched; only the confusion matrix changes (table B). "
          "At a matched sensitivity of 95% the two routes reach similar specificity, so the cheap, reversible route (threshold) is usually enough.\n")
    # ---------- B. cost-optimal threshold on the selected model
    s = best_seed(a.tag); j, n = load_run(a.tag, s); yv, yt, pv, pt = y[n["val_idx"]], y[n["test_idx"]], n["val_prob"], n["test_prob"]
    thr, vcost = choose_threshold(yv, pv)
    pi_tr = yv.mean(); odds = (C_FP / (C_FP + C_FN)) / (1 - C_FP / (C_FP + C_FN)) * (pi_tr / (1 - pi_tr)) / (CAMP_PREV / (1 - CAMP_PREV))
    thr_bayes = float(odds / (1 + odds))
    B = []
    for name, t in (("default 0.5", 0.5), ("cost-optimal (chosen on val)", thr), ("prior-shift Bayes (assumes calibration)", thr_bayes)):
        m = compute_metrics(yt, pt, t); tpr, fpr = m["recall"], 1 - m["specificity"]
        B.append(dict(rule=name, thr=round(t, 4), tn=m["tn"], fp=m["fp"], fn=m["fn"], tp=m["tp"], sens=round(tpr, 3), spec=round(m["specificity"], 3),
                      **{k: round(v, 4) for k, v in camp_stats(tpr, fpr).items()}))
    B = pd.DataFrame(B)
    P(f"## B. Cost-optimal threshold (model {a.tag}, seed {s}; threshold chosen on validation fold only)\n"
      f"Cost matrix: missed pneumonia = {C_FN:g}, false alarm = {C_FP:g}; camp prevalence = {CAMP_PREV:.0%} pneumonia (9:1 NORMAL).\n"
      f"Expected cost/child = {CAMP_PREV}·{C_FN:g}·(1-TPR) + {1-CAMP_PREV}·{C_FP:g}·FPR.  Test-set results (confusion on the dataset's own class mix; "
      f"ppv/npv/cost/accuracy re-weighted to camp prevalence):\n\n" + B.to_markdown(index=False) +
      f"\n\nReference costs per child: always-NORMAL = {CAMP_PREV*C_FN:.2f}, refer-everyone = {(1-CAMP_PREV)*C_FP:.2f}.\n")
    ch = compute_metrics(yt, pt, thr); tpr_c, fpr_c = ch["recall"], 1 - ch["specificity"]
    # ---------- figures
    fig, ax = plt.subplots(1, 3, figsize=(16, 4.6))
    fpr, tpr, th, cost = cost_curve(yv, pv); ax[0].plot(th[1:], cost[1:]); ax[0].axvline(thr, c="r", ls="--", label=f"chosen thr={thr:.3f}")
    ax[0].set_xscale("log"); ax[0].set_xlabel("threshold"); ax[0].set_ylabel("expected cost / child @ 10% prevalence (val)"); ax[0].legend()
    f2, t2, _ = roc_curve(yt, pt); ax[1].plot(f2, t2, label="ROC (test)"); ax[1].plot([0, 1], [0, 1], "k:")
    d5 = compute_metrics(yt, pt, 0.5); ax[1].scatter([fpr_c], [tpr_c], c="r", s=70, zorder=5, label=f"chosen thr {thr:.3f}")
    ax[1].scatter([1 - d5["specificity"]], [d5["recall"]], c="gray", s=50, zorder=5, label="thr 0.5"); ax[1].set_xlabel("FPR"); ax[1].set_ylabel("TPR"); ax[1].legend()
    pr, rc, _ = precision_recall_curve(yt, pt); ax[2].plot(rc, pr, label=f"PR (dataset prevalence {yt.mean():.2f})")
    adj = CAMP_PREV * t2 / np.maximum(CAMP_PREV * t2 + (1 - CAMP_PREV) * f2, 1e-12); ax[2].plot(t2, adj, label="PR re-weighted to camp prevalence 0.10")
    ax[2].scatter([tpr_c], [camp_stats(tpr_c, fpr_c)["ppv"]], c="r", s=70, zorder=5, label="chosen (camp)")
    ax[2].scatter([tpr_c], [ch["precision"]], c="orange", s=50, zorder=5, label="chosen (dataset)"); ax[2].set_xlabel("recall"); ax[2].set_ylabel("precision"); ax[2].legend(fontsize=7)
    plt.tight_layout(); plt.savefig(FIGS / "threshold_cost_roc_pr.png", dpi=130); plt.close()
    json.dump(dict(tag=a.tag, seed=int(s), thr=thr, prev=CAMP_PREV, cfn=C_FN, cfp=C_FP, val_expected_cost=vcost, test=ch,
                   test_camp=camp_stats(tpr_c, fpr_c)), open(RESULTS / "threshold.json", "w"), indent=1, default=float)
    open(RESULTS / "threshold_cost.md", "w").write("\n".join(out)); print("\n".join(out))


if __name__ == "__main__":
    main()
