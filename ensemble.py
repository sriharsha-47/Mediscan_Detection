"""Part 2, task 4: soft voting of Part-1 models + RandomForest / AdaBoost on penultimate-layer CNN features."""
import numpy as np, pandas as pd
from sklearn.ensemble import RandomForestClassifier, AdaBoostClassifier
from common import *
from train import load_ckpt, embed_all, get_device

try:
    from xgboost import XGBClassifier
except Exception:
    XGBClassifier = None


def main():
    set_seed(SEED); df = load_splits(); y = df.label.values; ix = get_idx(df, 0); yv, yt = y[ix["val"]], y[ix["test"]]
    members = {}
    for tag in ("arogyanet", "resnet18", "mobilenetv3"):
        for s in run_seeds(tag):
            _, n = load_run(tag, s); members[f"{tag}_s{s}"] = (n["val_prob"], n["test_prob"])
    if not members: print("no member runs"); return
    rows = []
    def add(name, pv, pt):
        mv, mt = compute_metrics(yv, pv), compute_metrics(yt, pt)
        rows.append(dict(model=name, val_roc=mv["roc_auc"], val_pr=mv["pr_auc"], test_roc=mt["roc_auc"], test_pr=mt["pr_auc"],
                         test_bal_acc=mt["bal_acc"], test_sens=mt["recall"], test_spec=mt["specificity"]))
    for k, (pv, pt) in members.items(): add(k, pv, pt)
    n_single = len(rows)
    def avg(keys): return np.mean([members[k][0] for k in keys], 0), np.mean([members[k][1] for k in keys], 0)
    groups = {t: [k for k in members if k.startswith(t + "_s")] for t in ("arogyanet", "resnet18", "mobilenetv3")}
    if len(groups["arogyanet"]) > 1: add("SOFT-VOTE arogyanet seeds", *avg(groups["arogyanet"]))
    fam = [t for t in groups if groups[t]]
    if len(fam) > 1:
        pv = np.mean([avg(groups[t])[0] for t in fam], 0); pt = np.mean([avg(groups[t])[1] for t in fam], 0)
        add("SOFT-VOTE family-average (" + "+".join(fam) + ")", pv, pt)
        add("SOFT-VOTE all members", *avg(list(members)))
    # ---- tree ensembles on CNN features
    tag = "arogyanet"; s = best_seed(tag); model, cfg = load_ckpt(MODELS / f"{tag}_s{s}.pt"); dev = get_device()
    imgs = load_array(df.path.tolist(), cfg["res"], cfg["preproc"]); meta = meta_features(df)
    Z = {k: embed_all(model, imgs, meta, ix[k], dev) for k in ("train", "val", "test")}
    clfs = {"RandomForest on CNN features": RandomForestClassifier(300, random_state=SEED, n_jobs=-1),
            "AdaBoost on CNN features": AdaBoostClassifier(n_estimators=200, random_state=SEED)}
    if XGBClassifier is not None: clfs["XGBoost on CNN features"] = XGBClassifier(n_estimators=300, max_depth=4, learning_rate=.05, random_state=SEED)
    for name, c in clfs.items():
        c.fit(Z["train"], y[ix["train"]]); add(name, c.predict_proba(Z["val"])[:, 1], c.predict_proba(Z["test"])[:, 1])
    T = pd.DataFrame(rows); T.to_csv(RESULTS / "ensemble_table.csv", index=False)
    singles = T.iloc[:n_single]; best = singles.loc[singles.val_pr.idxmax()]       # best member chosen on VAL
    ens = T[T.model.str.startswith("SOFT")]
    ks = list(members); E = np.stack([((members[k][1] >= .5).astype(int) != yt).astype(float) for k in ks])
    P = np.stack([members[k][1] for k in ks])
    errc = np.corrcoef(E)[np.triu_indices(len(ks), 1)] if len(ks) > 1 and E.std(1).min() > 0 else np.array([np.nan])
    txt = ("# Ensembles (auto-generated by ensemble.py); best single member chosen by validation PR-AUC = " + best.model + "\n\n"
           + T.round(4).to_markdown(index=False) +
           f"\n\nMean pairwise correlation of member probabilities (test): {np.corrcoef(P)[np.triu_indices(len(ks), 1)].mean():.3f}; "
           f"mean pairwise correlation of member ERRORS: {np.nanmean(errc):.3f}.\n"
           "If a soft-vote does not beat its best member: members trained on the same data/split make highly correlated errors "
           "(high error correlation => little variance to average away); the ensemble is then only as good as its typical member, and a single strong "
           "member can already sit near the noise floor of the test set. Differences smaller than seed-to-seed spread (see summary_runs.md) are not real.\n"
           "Tree models are fitted on training-set embeddings that the CNN has already fitted, so they can look over-optimistic on train and add little on val/test.\n")
    open(RESULTS / "ensemble_summary.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
