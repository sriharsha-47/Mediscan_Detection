"""Package the final model: models/final.pt, decision band, OOD (Mahalanobis) statistics, latency + file-size check."""
import json, shutil, time
import numpy as np
from common import *
from train import load_ckpt, embed_all, predict_probs


def main():
    set_seed(SEED); th = json.load(open(RESULTS / "threshold.json")); tag, s, thr = th["tag"], th["seed"], th["thr"]
    shutil.copy(MODELS / f"{tag}_s{s}.pt", MODELS / "final.pt")
    model, cfg = load_ckpt(MODELS / "final.pt")
    import torch
    dev = next(model.parameters()).device
    df = load_splits(); y = df.label.values; ix = get_idx(df, 0)
    imgs = load_array(df.path.tolist(), cfg["res"], cfg["preproc"]); meta = meta_features(df)
    Ztr, Zva = embed_all(model, imgs, meta, ix["train"], dev), embed_all(model, imgs, meta, ix["val"], dev)
    mu = Ztr.mean(0); cov = np.cov(Ztr.T) + 1e-3 * np.trace(np.cov(Ztr.T)) / Ztr.shape[1] * np.eye(Ztr.shape[1]); P = np.linalg.inv(cov)
    maha = lambda Z: np.sqrt(np.einsum("ij,jk,ik->i", Z - mu, P, Z - mu))
    ood_thr = float(1.3 * np.percentile(maha(Zva), 99))
    np.savez(MODELS / "ood_stats.npz", mu=mu, P=P)
    pv = predict_probs(model, imgs, meta, ix["val"], dev); yv = y[ix["val"]]
    thr_high = None
    for t in np.unique(pv[pv >= thr]):
        sel = pv >= t
        if sel.sum() >= 5 and yv[sel].mean() >= 0.95: thr_high = float(t); break
    thr_high = max(thr_high if thr_high is not None else 0.9, thr)
    info = dict(tag=tag, seed=s, res=cfg["res"], preproc=cfg["preproc"], thr_low=thr, thr_high=thr_high, ood_maha_thr=ood_thr,
                min_std=0.03, max_colour_diff=10.0, camp_prev=CAMP_PREV)
    json.dump(info, open(MODELS / "final_meta.json", "w"), indent=1)
    import predict
    predict._STATE.clear(); sample = DATA / df[df.split == "test"].path.iloc[0]
    for _ in range(5): predict.predict_path(sample)
    ts = []
    for _ in range(50):
        t0 = time.perf_counter(); predict.predict_path(sample); ts.append((time.perf_counter() - t0) * 1000)
    size = (MODELS / "final.pt").stat().st_size / 1e6
    dep = dict(median_ms=float(np.median(ts)), p95_ms=float(np.percentile(ts, 95)), size_mb=size, device="cpu",
               meets_200ms=bool(np.percentile(ts, 95) < 200), meets_25MB=bool(size < 25))
    json.dump(dep, open(RESULTS / "deploy.json", "w"), indent=1)
    txt = (f"# Deployment constraints (auto-generated by make_final.py)\nEnd-to-end single-image latency on this machine's CPU (read file + resize + forward + OOD check): "
           f"median {dep['median_ms']:.1f} ms, p95 {dep['p95_ms']:.1f} ms (limit 200 ms) -> {'PASS' if dep['meets_200ms'] else 'FAIL'}.\n"
           f"Model file: {size:.2f} MB (limit 25 MB) -> {'PASS' if dep['meets_25MB'] else 'FAIL'}.\n"
           f"Decision rule: p < {thr:.3f} -> NORMAL;  {thr:.3f} <= p < {thr_high:.3f} -> LOW CONFIDENCE, refer to clinician;  p >= {thr_high:.3f} -> PNEUMONIA suspected.\n"
           f"Input guards: blank image (std < {info['min_std']}), colour photo (channel diff > {info['max_colour_diff']}), embedding Mahalanobis distance > {ood_thr:.1f}.\n")
    open(RESULTS / "deploy.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
