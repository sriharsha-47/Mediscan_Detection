"""Part 2, task 3: random search + unregularised vs regularised learning curves + early-stopping analysis."""
import argparse, json
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from common import *
from train import run_one


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=12); ap.add_argument("--tune_epochs", type=int, default=8)
    ap.add_argument("--curve_epochs", type=int, default=30); ap.add_argument("--res", type=int, default=224)
    ap.add_argument("--quick", action="store_true"); a = ap.parse_args()
    if a.quick: a.tune_epochs, a.curve_epochs = 2, 6
    extra = dict(max_train=300) if a.quick else {}
    rng = np.random.RandomState(SEED); rows = []
    for i in range(a.n):
        hp = dict(lr=float(10 ** rng.uniform(-4, -2.5)), bs=int(rng.choice([16, 32, 64])),
                  dropout=float(rng.choice([0, .1, .3, .5])), wd=float(10 ** rng.uniform(-6, -2)))
        r = run_one(dict(model="arogyanet", res=a.res, epochs=a.tune_epochs, aug="safe", **hp, **extra), 0, f"tune_{i}", save=False, verbose=False)
        rows.append(dict(trial=i, **hp, best_val_loss=min(h["val_loss"] for h in r["history"]), val_roc_auc=r["val"]["roc_auc"],
                         val_pr_auc=r["val"]["pr_auc"], best_epoch=r["best_epoch"]))
        print(rows[-1], flush=True)
    T = pd.DataFrame(rows).sort_values("best_val_loss"); T.to_csv(RESULTS / "tuning.csv", index=False)
    best = T.iloc[0]; hp = {k: (int(best[k]) if k == "bs" else float(best[k])) for k in ("lr", "bs", "dropout", "wd")}
    json.dump(hp, open(RESULTS / "best_hparams.json", "w"), indent=1)

    E = a.curve_epochs
    ru = run_one(dict(model="arogyanet", res=a.res, epochs=E, aug="none", dropout=0.0, wd=0.0, lr=hp["lr"], bs=hp["bs"],
                      early_stop=False, **extra), 0, "curve_unreg", verbose=False)
    rr = run_one(dict(model="arogyanet", res=a.res, epochs=E, aug="safe", early_stop=True, patience=5, **hp, **extra), 0, "curve_reg", verbose=False)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    for a_, r, t in ((ax[0], ru, "Unregularised (no aug, dropout 0, wd 0, no early stop)"), (ax[1], rr, "Regularised (tuned hp, aug, early stop)")):
        e = [h["epoch"] for h in r["history"]]
        a_.plot(e, [h["train_loss"] for h in r["history"]], label="train loss"); a_.plot(e, [h["val_loss"] for h in r["history"]], label="val loss")
        a_.axvline(r["best_epoch"], ls="--", c="k", label=f"min val loss @ epoch {r['best_epoch']}"); a_.set_title(t, fontsize=9)
        a_.set_xlabel("epoch"); a_.legend()
    plt.tight_layout(); plt.savefig(FIGS / "curves_unreg_vs_reg.png", dpi=130); plt.close()
    hu, hr = ru["history"], rr["history"]
    txt = f"""# Hyper-parameter search & regularisation (auto-generated by tune.py)
**Budget:** random search, {a.n} trials x {a.tune_epochs} epochs, 1 seed, validation fold 0; space: lr ~ logU[1e-4, 3e-3], batch size in {{16,32,64}},
dropout in {{0,.1,.3,.5}}, weight decay ~ logU[1e-6, 1e-2]; selection criterion = lowest validation loss.

{T.head(5).round(5).to_markdown(index=False)}

**Chosen:** {hp}

## Overfitting
* Unregularised run: validation loss is lowest at **epoch {ru['best_epoch']}** ({min(h['val_loss'] for h in hu):.4f}); overfitting begins right after it.
  By epoch {len(hu)} train loss = {hu[-1]['train_loss']:.4f} but val loss = {hu[-1]['val_loss']:.4f}.
* Regularised run with early stopping stopped at epoch **{len(hr)}** of a possible {E} (best epoch {rr['best_epoch']}, val loss {min(h['val_loss'] for h in hr):.4f}).
  Early stopping saved {E - len(hr)} epochs of compute and avoided a val-loss rise of {hu[-1]['val_loss'] - min(h['val_loss'] for h in hu):+.4f} seen in the unregularised run.
Figure: figures/curves_unreg_vs_reg.png
"""
    open(RESULTS / "tuning.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
