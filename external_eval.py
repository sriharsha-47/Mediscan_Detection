"""Part 2, task 6: THE ONLY SCRIPT THAT TOUCHES THE EXTERNAL HOSPITAL DATA - run once.
Evaluates (a) the final model and (b) the CLAHE-retrained model at thresholds fixed on INTERNAL validation data."""
import argparse, json, datetime
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.stats import ks_2samp
from common import *
from train import load_ckpt, predict_probs, get_device
from threshold_cost import camp_stats

LOCK = RESULTS / ".external_done"


def external_files(max_per_class=0):
    rows = []
    for p in sorted(EXTERNAL.rglob("*")):
        if p.suffix.lower() not in IMG_EXT: continue
        parts = [x.lower() for x in p.relative_to(EXTERNAL).parts]
        if "masks" in parts: continue
        if "normal" in parts: lab = 0
        elif any("viral" in x for x in parts): lab = 1
        else: continue
        rows.append(dict(path=str(p), label=lab))
    d = pd.DataFrame(rows)
    if len(d) == 0: raise FileNotFoundError(f"No Normal / Viral Pneumonia images under {EXTERNAL}")
    if max_per_class: d = d.groupby("label", group_keys=False).apply(lambda g: g.sample(min(len(g), max_per_class), random_state=SEED))
    return d.reset_index(drop=True)


EXTERNAL = DATA / "covid"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--force_invalid", action="store_true",
                                                    help="re-run anyway; the result is then NOT a valid held-out estimate")
    ap.add_argument("--max_per_class", type=int, default=0); a = ap.parse_args()
    if LOCK.exists() and not a.force_invalid:
        raise SystemExit(f"External data already used ({LOCK.read_text()}). Re-running would turn it into a tuning set.")
    set_seed(SEED); ext = external_files(a.max_per_class); ye = ext.label.values; dev = get_device()
    df = load_splits(); y = df.label.values; ix = get_idx(df, 0); th = json.load(open(RESULTS / "threshold.json"))
    stats = []
    for p in ext.path:
        g = read_gray(p); stats.append((g.mean() / 255, g.std() / 255, g.shape[0], g.shape[1]))
    ext[["mean", "std", "h", "w"]] = np.array(stats)
    rows = []; tags = {"final (ArogyaNet)": th["tag"], "CLAHE fix (retrained)": th["tag"] + "_clahe"}
    for name, tag in tags.items():
        if not run_seeds(tag): continue
        s = th["seed"] if tag == th["tag"] else best_seed(tag); j, n = load_run(tag, s)
        thr = th["thr"] if tag == th["tag"] else choose_threshold(y[n["val_idx"]], n["val_prob"])[0]
        model, cfg = load_ckpt(MODELS / f"{tag}_s{s}.pt")
        imgs = load_array(ext.path.tolist(), cfg["res"], cfg["preproc"], key="external")
        pe = predict_probs(model, imgs, np.zeros((len(ext), 3), np.float32), np.arange(len(ext)), dev)
        for where, yy, pp in (("internal test", y[n["test_idx"]], n["test_prob"]), ("EXTERNAL hospital", ye, pe)):
            m = compute_metrics(yy, pp, thr); c = camp_stats(m["recall"], 1 - m["specificity"])
            rows.append(dict(model=name, data=where, thr=round(thr, 4), roc_auc=m["roc_auc"], pr_auc=m["pr_auc"], sens=m["recall"], spec=m["specificity"],
                             bal_acc=m["bal_acc"], acc=m["acc"], camp_ppv=c["ppv"], camp_npv=c["npv"], camp_cost_per_child=c["cost_per_child"]))
    R = pd.DataFrame(rows).round(3); R.to_csv(RESULTS / "external_table.csv", index=False)
    d = {}
    for m_ in R.model.unique():
        i, e = R[(R.model == m_) & (R.data == "internal test")].iloc[0], R[(R.model == m_) & (R.data == "EXTERNAL hospital")].iloc[0]
        d[m_] = {k: round(float(e[k] - i[k]), 3) for k in ("roc_auc", "pr_auc", "sens", "spec", "bal_acc")}
    prim = df.groupby("label_name")[["mean", "std", "h", "w"]].mean().round(3); extg = ext.groupby("label")[["mean", "std", "h", "w"]].mean().round(3)
    extg.index = [CLASSES[i] for i in extg.index]
    ks = {f: round(ks_2samp(df[f], ext[f]).statistic, 3) for f in ("mean", "std", "h", "w")}
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.6))
    for a_, f in zip(ax, ("mean", "std")):
        a_.hist(df[f], bins=40, density=True, alpha=.5, label="Arogya (Guangzhou, paediatric AP)"); a_.hist(ext[f], bins=40, density=True, alpha=.5, label="External (adult-dominated PA)")
        a_.set_title(f"per-image {f}"); a_.legend(fontsize=7)
    plt.tight_layout(); plt.savefig(FIGS / "external_pixel_shift.png", dpi=130); plt.close()
    txt = ("# External generalisation test (run once; auto-generated by external_eval.py)\n" + R.to_markdown(index=False) +
           f"\n\nChange (external - internal): {json.dumps(d)}\n\n## Distribution mismatch (pixel statistics, Part 1 vs external)\nPrimary:\n{prim.to_markdown()}\n\nExternal:\n{extg.to_markdown()}\n\n"
           f"Two-sample KS statistics (primary vs external, 0 = identical, 1 = disjoint): {ks}\nFigure: figures/external_pixel_shift.png\n"
           + ("\n**WARNING: forced re-run - this is no longer a valid held-out estimate.**\n" if a.force_invalid else ""))
    open(RESULTS / "external_summary.md", "w").write(txt); print(txt)
    LOCK.write_text(datetime.datetime.now().isoformat())


if __name__ == "__main__":
    main()
