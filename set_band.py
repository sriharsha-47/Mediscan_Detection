"""Define the three-zone decision band from VALIDATION data and report what it does on the locked test set.
  p <  t_low            -> NORMAL            (t_low  = largest threshold with val sensitivity >= 98%)
  t_low <= p < t_high   -> LOW CONFIDENCE    (refer to a clinician)
  p >= t_high           -> PNEUMONIA suspected (t_high = smallest threshold with val specificity >= 99%)
Only NORMAL clears a child; the other two zones both lead to clinician review. Keeps ood_maha_thr in models/final_meta.json."""
import json
import numpy as np
from sklearn.metrics import roc_curve
from common import *

TARGET_SENS, TARGET_SPEC = 0.98, 0.99


def main():
    th = json.load(open(RESULTS / "threshold.json")); tag, s = th["tag"], th["seed"]
    df = load_splits(); y = df.label.values; _, n = load_run(tag, s)
    yv, pv, yt, pt = y[n["val_idx"]], n["val_prob"], y[n["test_idx"]], n["test_prob"]
    fpr, tpr, thr = roc_curve(yv, pv)
    fix = lambda t: float(np.max(pv) + 1e-6) if not np.isfinite(t) else float(t)
    t_low = fix(thr[np.where(tpr >= TARGET_SENS)[0][0]])
    t_high = fix(thr[np.where(fpr <= 1 - TARGET_SPEC)[0][-1]])
    warn = ""
    if t_high <= t_low: warn = "\n**WARNING: t_high <= t_low, the band is empty.**\n"; t_high = t_low
    zone = lambda p: np.where(p < t_low, 0, np.where(p < t_high, 1, 2))
    zt = zone(pt); sick, well = yt == 1, yt == 0
    a = np.array([np.mean(zt[sick] == k) for k in range(3)]); b = np.array([np.mean(zt[well] == k) for k in range(3)])
    P = CAMP_PREV; share = P * a + (1 - P) * b
    sens_lo, sens_hi = clopper_pearson(int((zt[sick] != 0).sum()), int(sick.sum()))
    rows = ["| zone | test images | camp: per 1,000 children | of which sick | of which healthy |", "|---|---|---|---|---|"]
    for k, nm in enumerate(["NORMAL (cleared)", "LOW CONFIDENCE (refer)", "PNEUMONIA suspected (refer)"]):
        rows.append(f"| {nm} | {int((zt == k).sum())} | {1000*share[k]:.0f} | {1000*P*a[k]:.1f} | {1000*(1-P)*b[k]:.1f} |")
    txt = (f"# Decision band (auto-generated by set_band.py; thresholds chosen on validation data only)\nModel {tag}, seed {s}.\n"
           f"t_low = {t_low:.4f} (val sensitivity >= {TARGET_SENS:.0%}), t_high = {t_high:.4f} (val specificity >= {TARGET_SPEC:.0%}); "
           f"the cost-optimal single threshold was {th['thr']:.4f}.{warn}\n\n" + "\n".join(rows) +
           f"\n\nOn the locked test set, children NOT cleared as NORMAL (i.e. referred): sensitivity {1-a[0]:.3f} "
           f"(95% CI {sens_lo:.3f}-{sens_hi:.3f}); healthy children cleared: {b[0]:.3f}.\n"
           f"At 10% camp prevalence: NPV of the NORMAL zone = {(1-P)*b[0]/share[0]:.4f}; share of all children referred = {1-share[0]:.3f}; "
           f"PPV of the PNEUMONIA zone = {P*a[2]/share[2] if share[2] else float('nan'):.3f}.\n"
           "Thresholds chosen on validation do not transfer exactly to test (see weights_vs_threshold in threshold_cost.md): report these test numbers as they are.\n")
    f = MODELS / "final_meta.json"; m = json.load(open(f)); m["thr_low"], m["thr_high"] = t_low, t_high
    json.dump(m, open(f, "w"), indent=1); open(RESULTS / "band.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()