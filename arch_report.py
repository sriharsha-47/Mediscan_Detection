"""Part 1, task 7a: architecture table (layer, output shape, params) + network diagram."""
import torch
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch
from common import *
from arogyanet import ArogyaNet, count_params


def table(model, res=224):
    rows = []
    hooks = [m.register_forward_hook(lambda mod, i, o, n=n: rows.append((n, tuple(o.shape), count_params(mod))))
             for n, m in model.named_children()]
    model.eval()
    with torch.no_grad(): model(torch.zeros(2, 1, res, res), torch.zeros(2, 3))
    for h in hooks: h.remove()
    return rows


def main():
    set_seed(SEED)
    txt = ["# ArogyaNet architecture (auto-generated by arch_report.py)\n"]
    for name, kw in [("ArogyaNet (image only)", {}), ("no residual", dict(use_res=False)),
                     ("no SE", dict(use_se=False)), ("two-branch (+metadata)", dict(use_meta=True))]:
        m = ArogyaNet(**kw); rows = table(m)
        txt.append(f"## {name} — total parameters: **{count_params(m):,}** (limit 2,000,000)\n")
        txt.append("| layer | output shape (B,C,H,W) | params |\n|---|---|---|")
        for n, s, p in rows: txt.append(f"| {n} | {s} | {p:,} |")
        txt.append(f"| **total** | | **{count_params(m):,}** |\n")
    open(RESULTS / "arch_table.md", "w").write("\n".join(txt)); print("\n".join(txt))

    fig, ax = plt.subplots(figsize=(15, 4.2)); ax.set_xlim(0, 15); ax.set_ylim(0, 4.2); ax.axis("off")
    labels = ["Input\n1x224x224", "BN + Stem\n3x3 s2\n16x112x112", "Block1\n32x56x56", "Block2\n64x28x28",
              "Block3\n128x14x14", "Block4\n192x7x7", "Block5\n192x7x7", "GAP\n192", "Dropout\n+ Linear(1)"]
    xs = [0.3 + i * 1.6 for i in range(len(labels))]
    for i, (x, l) in enumerate(zip(xs, labels)):
        col = "#cfe8ff" if 2 <= i <= 6 else "#eeeeee"
        ax.add_patch(FancyBboxPatch((x, 1.0), 1.25, 1.3, boxstyle="round,pad=0.03", fc=col, ec="k"))
        ax.text(x + .62, 1.65, l, ha="center", va="center", fontsize=8)
        if i: ax.add_patch(FancyArrowPatch((xs[i-1] + 1.28, 1.65), (x - .03, 1.65), arrowstyle="->", mutation_scale=12))
    for i in range(2, 7):   # residual arcs
        ax.add_patch(FancyArrowPatch((xs[i] - .1, 2.35), (xs[i] + 1.35, 2.35), connectionstyle="arc3,rad=-0.6",
                                     arrowstyle="->", color="tab:green", mutation_scale=12))
    ax.text(7.5, 3.8, "green arcs = residual shortcuts (D1)   |   each Block = 2x(depthwise3x3 + pointwise1x1) -> SE (D2) -> add -> ReLU6",
            ha="center", fontsize=9)
    ax.text(7.5, 0.3, "Two-branch variant: [mean, aspect, log-area] -> BN -> Dense16 -> Dense16 ---> concatenated with GAP vector", ha="center", fontsize=9)
    plt.savefig(FIGS / "arogyanet_diagram.png", dpi=140, bbox_inches="tight"); plt.close()


if __name__ == "__main__":
    main()
