"""Part 2, task 2: full metric set at the chosen threshold + 5-fold stratified (patient-grouped) CV on the training pool."""
import argparse, json
import numpy as np, pandas as pd
from common import *
from train import run_one


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--epochs", type=int, default=20); ap.add_argument("--res", type=int, default=224)
    ap.add_argument("--quick", action="store_true"); a = ap.parse_args()
    hp = json.load(open(RESULTS / "best_hparams.json")); th = json.load(open(RESULTS / "threshold.json")); thr = th["thr"]
    cfg = dict(model="arogyanet", epochs=2 if a.quick else a.epochs, res=a.res, **hp, **(dict(max_train=300) if a.quick else {}))
    df = load_splits(); y = df.label.values; rows = []
    for f in range(5):   # held-out fold f; fold (f+1)%5 is used only for early stopping
        r = run_one(cfg, 0, f"cv_fold{f}", val_fold=(f + 1) % 5, holdout_fold=f, verbose=False)
        m = compute_metrics(y[r["ix"]["hold"]], r["probs"]["hold"], thr); m["fold"] = f; rows.append(m)
    D = pd.DataFrame(rows); D.to_csv(RESULTS / "cv_folds.csv", index=False)
    cols = ["acc", "precision", "recall", "specificity", "f1", "roc_auc", "pr_auc", "bal_acc"]
    summ = {c: fmt(D[c].mean(), D[c].std(ddof=1)) for c in cols}
    t = th["test"]
    final = {c: f"{t[c]:.3f}" for c in cols}
    txt = (f"# 5-fold CV on training pool at fixed threshold {thr:.4f} (auto-generated by cv_eval.py)\n\n"
           + D[["fold"] + cols].round(3).to_markdown(index=False) + "\n\n**mean ± std:**\n\n"
           + pd.DataFrame([summ, final], index=["5-fold CV", "locked test (single model)"]).to_markdown() +
           "\n\nConfusion matrix at the chosen threshold on the locked test set: "
           f"TN={t['tn']} FP={t['fp']} FN={t['fn']} TP={t['tp']}.\n\n"
           "**Why accuracy alone is the wrong headline:** at 9:1 prevalence a model that never flags anyone scores 90% accuracy while missing every sick child, "
           "and accuracy weights a missed pneumonia the same as a false alarm although the former is ~20x costlier. "
           "Sensitivity, specificity, PPV/NPV at the deployment prevalence and the expected cost are what describe safety.\n"
           "(Note: the threshold was chosen on validation fold 0, which is a training fold of some CV splits - a small optimistic bias, stated openly.)\n")
    open(RESULTS / "cv_table.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
