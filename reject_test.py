"""Part 2, task 7: the tool must NOT confidently report pneumonia on a dog photo or a blank image."""
import numpy as np, cv2
from common import *
from predict import predict_path

PROBES = ROOT / "tests" / "probes"


def main():
    PROBES.mkdir(parents=True, exist_ok=True); rng = np.random.RandomState(SEED)
    cv2.imwrite(str(PROBES / "blank_white.png"), np.full((512, 512), 255, np.uint8))
    cv2.imwrite(str(PROBES / "blank_black.png"), np.zeros((512, 512), np.uint8))
    cv2.imwrite(str(PROBES / "uniform_grey.png"), np.full((512, 512), 128, np.uint8))
    cv2.imwrite(str(PROBES / "gaussian_noise_grey.png"), rng.randint(0, 255, (512, 512), np.uint8))
    cv2.imwrite(str(PROBES / "colour_blobs.jpg"), cv2.resize(rng.randint(0, 255, (6, 6, 3), np.uint8), (512, 512), interpolation=cv2.INTER_CUBIC))
    cv2.imwrite(str(PROBES / "grey_stripes.png"), np.tile((np.arange(512) % 64 * 4).astype(np.uint8), (512, 1)))
    files = sorted(PROBES.glob("*.*")); dog = [f for f in files if "dog" in f.name.lower()]
    df = load_splits(); real = [DATA / p for p in df[df.split == "test"].path.sample(6, random_state=SEED)]
    rows = ["| input | result | prob | message |", "|---|---|---|---|"]; bad = 0
    for f in files + real:
        r = predict_path(f); pr = "" if r["prob"] is None else f"{r['prob']:.3f}"
        kind = "REAL X-RAY (control)" if f in real else f.name
        if f not in real and r["status"] == "ok": bad += 1
        rows.append(f"| {kind} | {r['label']} | {pr} | {r['message']} |")
    note = "" if dog else "\n**No dog photo found: put one at tests/probes/dog.jpg and re-run `python reject_test.py`.**\n"
    txt = "# Rejection test (auto-generated by reject_test.py)\n" + "\n".join(rows) + f"\n\nNon-X-ray inputs that were NOT rejected (any NORMAL/PNEUMONIA/LOW-CONFIDENCE answer): **{bad}** (must be 0).\n" + note
    open(RESULTS / "rejection_test.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()