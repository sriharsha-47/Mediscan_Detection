"""Part 2, task 5: PCA / t-SNE of penultimate-layer embeddings, k-means agreement, what the mistakes share."""
import json
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE
from sklearn.cluster import KMeans
from sklearn.metrics import adjusted_rand_score, normalized_mutual_info_score
from common import *
from train import load_ckpt, embed_all, get_device


def purity(y, c): return sum(np.bincount(y[c == k]).max() for k in np.unique(c)) / len(y)


def main():
    set_seed(SEED); th = json.load(open(RESULTS / "threshold.json")); tag, s, thr = th["tag"], th["seed"], th["thr"]
    df = load_splits(); y = df.label.values; ix = get_idx(df, 0); te = ix["test"]
    model, cfg = load_ckpt(MODELS / f"{tag}_s{s}.pt"); imgs = load_array(df.path.tolist(), cfg["res"], cfg["preproc"])
    Z = embed_all(model, imgs, meta_features(df), te, get_device()); yt = y[te]
    _, n = load_run(tag, s); p = n["test_prob"]; pred = (p >= thr).astype(int); wrong = pred != yt
    P2 = PCA(2, random_state=SEED).fit_transform(Z)
    T2 = TSNE(2, perplexity=min(30, max(5, len(te) // 4)), random_state=SEED, init="pca").fit_transform(Z)
    fig, ax = plt.subplots(2, 2, figsize=(11, 9))
    for r, (E, nm) in enumerate(((P2, "PCA"), (T2, "t-SNE"))):
        for k, c in enumerate(["tab:blue", "tab:red"]): ax[r, 0].scatter(*E[yt == k].T, s=8, c=c, alpha=.6, label=CLASSES[k])
        ax[r, 0].set_title(f"{nm} - true class"); ax[r, 0].legend()
        ax[r, 1].scatter(*E[~wrong].T, s=8, c="lightgray", label="correct"); ax[r, 1].scatter(*E[wrong].T, s=25, c="k", marker="x", label="misclassified")
        ax[r, 1].set_title(f"{nm} - correct / incorrect @ thr {thr:.3f}"); ax[r, 1].legend()
    plt.tight_layout(); plt.savefig(FIGS / "embeddings_pca_tsne.png", dpi=130); plt.close()
    km = KMeans(2, n_init=10, random_state=SEED).fit_predict(Z)
    ari, nmi, pur = adjusted_rand_score(yt, km), normalized_mutual_info_score(yt, km), purity(yt, km)
    d = df.iloc[te].copy(); d["wrong"] = wrong; d["prob"] = p; d["kind"] = np.where(~wrong, "correct", np.where(yt == 1, "missed pneumonia (FN)", "false alarm (FP)"))
    G = d.groupby("kind").agg(n=("prob", "size"), mean_brightness=("mean", "mean"), contrast_std=("std", "mean"), mean_area=("area", "mean"),
                              mean_aspect=("aspect", "mean"), mean_prob=("prob", "mean"),
                              pct_bacterial=("path", lambda x: 100 * np.mean(["bacteria" in v for v in x])),
                              pct_virus=("path", lambda x: 100 * np.mean(["virus" in v for v in x]))).round(3)
    bad = d[d.wrong].sort_values("prob"); sel = pd.concat([bad.head(3), bad.tail(3)]).drop_duplicates()
    if len(sel):
        fig, ax = plt.subplots(1, len(sel), figsize=(3 * len(sel), 3.4), squeeze=False)
        for a_, (_, r) in zip(ax[0], sel.iterrows()):
            a_.imshow(read_gray(r.path), cmap="gray"); a_.axis("off"); a_.set_title(f"{r.kind}\np={r.prob:.2f}", fontsize=8)
        plt.tight_layout(); plt.savefig(FIGS / "misclassified_examples.png", dpi=120); plt.close()
    txt = (f"# Feature-space analysis (model {tag}, seed {s}, test set; auto-generated by embeddings.py)\n"
           f"k-means (k=2) vs true labels: ARI = {ari:.3f}, NMI = {nmi:.3f}, purity = {pur:.3f} (majority-class purity = {max(yt.mean(), 1-yt.mean()):.3f}).\n\n"
           + G.to_markdown() + "\n\nFigures: figures/embeddings_pca_tsne.png, figures/misclassified_examples.png.\n"
           "Interpretation guide: compare the rows - do errors cluster at particular brightness/contrast/size values, in one pathogen type "
           "(bacterial vs viral), or near the class boundary (mean_prob close to the threshold)? Write what YOU observe in the report.\n")
    open(RESULTS / "embeddings_summary.md", "w").write(txt); print(txt)


if __name__ == "__main__":
    main()
