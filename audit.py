"""Part 1, tasks 1-3: inventory, pixel statistics, duplicates/leakage, validation-set confidence interval."""
import re
import numpy as np, pandas as pd, cv2
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.metrics import roc_auc_score
from scipy.stats import ks_2samp
from common import *

HAM_T = 4   # pHash Hamming distance (out of 64) treated as "near-duplicate"


def thumb(p):
    return cv2.resize(read_gray(p), (32, 32), interpolation=cv2.INTER_AREA).astype(np.float32).ravel()


def main():
    set_seed(SEED)
    df = load_manifest(force=True)
    out = []; P = out.append
    P("# Audit numbers (auto-generated by audit.py)\n")

    # ---- 1. inventory + pixel statistics
    inv = pd.crosstab(df.orig_split, df.label_name); inv["total"] = inv.sum(1); inv.loc["ALL"] = inv.sum()
    inv.to_csv(RESULTS / "audit_inventory.csv")
    P("## 1. Inventory (original Kaggle split)\n" + inv.to_markdown() + "\n")
    P(f"Image modes: {df['mode'].value_counts().to_dict()}.  Pixel-identical-channel greyscale: "
      f"{int(df.true_gray.sum())} / {len(df)}  ({100*df.true_gray.mean():.1f}%).\n")
    desc = df.groupby("label_name")[["h", "w", "aspect", "area", "mean", "std"]].agg(["mean", "median", "std"]).round(3)
    desc.columns = ["_".join(c) for c in desc.columns]
    P("### Per-class size / brightness summary\n" + desc.T.to_markdown() + "\n")
    rows = []
    for f in ["mean", "std", "h", "w", "aspect", "area"]:
        a, b = df[df.label == 0][f], df[df.label == 1][f]
        auc = roc_auc_score(df.label, df[f])
        rows.append(dict(feature=f, single_feature_AUC=round(auc, 3), KS_stat=round(ks_2samp(a, b).statistic, 3)))
    sf = pd.DataFrame(rows)
    P("### Can ONE metadata number separate the classes? (AUC 0.5 = no; far from 0.5 = shortcut)\n"
      + sf.to_markdown(index=False) + "\n")

    fig, ax = plt.subplots(2, 3, figsize=(15, 8))
    for a, f, t in zip(ax.ravel(), ["mean", "std", "h", "w", "aspect", "area"],
                       ["mean brightness", "contrast (std)", "height px", "width px", "aspect ratio w/h", "area px"]):
        for c, col in zip(CLASSES, ["tab:blue", "tab:red"]):
            a.hist(df[df.label_name == c][f], bins=40, alpha=.55, label=c, color=col, density=True)
        a.set_title(t); a.legend()
    plt.tight_layout(); plt.savefig(FIGS / "audit_class_histograms.png", dpi=130); plt.close()

    rng = np.random.RandomState(SEED); fig = plt.figure(figsize=(6, 4))
    for c, col in zip([0, 1], ["tab:blue", "tab:red"]):
        sub = df[df.label == c].sample(min(300, (df.label == c).sum()), random_state=SEED)
        hist = np.zeros(256)
        for p in sub.path:
            hist += np.bincount(cv2.resize(read_gray(p), (64, 64)).ravel(), minlength=256)
        plt.plot(hist / hist.sum(), label=CLASSES[c], color=col)
    plt.legend(); plt.title("Pixel-intensity histogram (300 imgs/class)"); plt.xlabel("grey level")
    plt.tight_layout(); plt.savefig(FIGS / "audit_pixel_hist.png", dpi=130); plt.close()

    # ---- 2. duplicates and leakage
    md5g = df.groupby("md5").filter(lambda g: len(g) > 1)
    n_exact_groups = md5g.md5.nunique(); n_exact_extra = len(md5g) - n_exact_groups
    cross_exact = sum(1 for _, g in md5g.groupby("md5") if g.orig_split.nunique() > 1)
    P(f"## 2. Duplicates / leakage\nExact byte-duplicates: {n_exact_groups} groups, {n_exact_extra} redundant files; "
      f"{cross_exact} groups span more than one original split.\n")

    D = hamming_matrix(df.phash.tolist())
    idx = np.argwhere(np.triu(D <= HAM_T, 1))
    pairs = pd.DataFrame(dict(i=idx[:, 0], j=idx[:, 1]))
    pairs["dist"] = D[pairs.i, pairs.j]
    for s in ("i", "j"):
        pairs["split_" + s] = df.orig_split.values[pairs[s]]; pairs["patient_" + s] = df.patient.values[pairs[s]]
        pairs["label_" + s] = df.label.values[pairs[s]]; pairs["path_" + s] = df.path.values[pairs[s]]
    if len(pairs) and len(pairs) < 30000:
        T = {k: thumb(df.path.values[k]) for k in set(pairs.i) | set(pairs.j)}
        pairs["corr"] = [np.corrcoef(T[a], T[b])[0, 1] for a, b in zip(pairs.i, pairs.j)]
    else:
        pairs["corr"] = np.nan
    pairs.to_csv(RESULTS / "near_duplicates.csv", index=False)
    pairs["within"] = pairs.split_i == pairs.split_j
    pairs["same_patient"] = pairs.patient_i == pairs.patient_j
    pairs["pair_type"] = [("within " + a) if a == b else " vs ".join(sorted((a, b))) for a, b in zip(pairs.split_i, pairs.split_j)]
    P(f"Near-duplicate pairs (pHash Hamming <= {HAM_T}/64): {len(pairs)} total; "
      f"{int(pairs.within.sum())} within a split, {int((~pairs.within).sum())} across splits.\n")
    if len(pairs):
        P(pairs.groupby("pair_type").agg(pairs=("dist", "size"), same_patient=("same_patient", "sum"),
                                         mean_corr=("corr", "mean")).round(3).to_markdown() + "\n")

    tr = np.where(df.orig_split == "train")[0]; te = np.where(df.orig_split == "test")[0]
    sub = D[np.ix_(tr, te)]
    leak = (sub.min(0) <= HAM_T)
    P(f"**Train->test leakage:** {int(leak.sum())} of {len(te)} test images ({100*leak.mean():.1f}%) have a train "
      f"near-duplicate (Hamming <= {HAM_T}).\n")
    # File-name IDs: PNEUMONIA names are person<N>_<pathogen>_<k>; the number is only meaningful within a pathogen series.
    # NORMAL names come from two series (IM-xxxx and NORMAL2-IM-xxxx) whose numbers are NOT shared patient IDs.
    def pkey(p):
        n = p.split("/")[-1]; m = re.match(r"(person\d+_(?:bacteria|virus))_", n)
        if m: return m.group(1)
        return ("NORMAL2-" if "NORMAL2" in n else "") + (re.search(r"IM-\d{4}", n).group(0) if re.search(r"IM-\d{4}", n) else n)
    df["pkey"] = df.path.map(pkey)
    naive_both = set(df.patient[df.orig_split == "train"]) & set(df.patient[df.orig_split == "test"])
    for nm, mask in (("PNEUMONIA (person+pathogen key)", df.label == 1), ("NORMAL (series-aware key)", df.label == 0)):
        a_, b_ = set(df.pkey[mask & (df.orig_split == "train")]), set(df.pkey[mask & (df.orig_split == "test")])
        both = a_ & b_; n_te = int(df.pkey[mask & (df.orig_split == "test")].isin(both).sum())
        P(f"**Patient overlap, {nm}:** {len(both)} IDs in both train and test ({n_te} test images).\n")
    P(f"(A naive parser that ignores pathogen / series reported {len(naive_both)} shared IDs; these are ID collisions, not shared children - "
      "e.g. person100_virus in train vs person100_bacteria in test. Patient-level leakage cannot be confirmed from file names alone for NORMAL images.)\n")

    order = np.dstack(np.unravel_index(np.argsort(sub, axis=None), sub.shape))[0]
    chosen, seen = [], set()
    for a, b in order:
        if b in seen: continue
        seen.add(b); chosen.append((tr[a], te[b], sub[a, b]))
        if len(chosen) == 5: break
    fig, ax = plt.subplots(5, 2, figsize=(6, 15))
    for r, (a, b, d) in enumerate(chosen):
        for c, k, nm in ((0, a, "train"), (1, b, "test")):
            ax[r, c].imshow(read_gray(df.path.values[k]), cmap="gray"); ax[r, c].axis("off")
            ax[r, c].set_title(f"{nm}: {df.path.values[k].split('/')[-1]}", fontsize=7)
        ax[r, 0].text(0, -0.12, f"Hamming={d}", transform=ax[r, 0].transAxes, fontsize=8)
    plt.tight_layout(); plt.savefig(FIGS / "audit_worst5_train_test_pairs.png", dpi=130); plt.close()
    P("Worst five train/test pairs: `figures/audit_worst5_train_test_pairs.png` "
      + str([(df.path.values[a].split('/')[-1], df.path.values[b].split('/')[-1], int(d)) for a, b, d in chosen]) + "\n")

    # ---- 3. the 16-image validation set
    k, n = 16, 16
    lo, hi = clopper_pearson(k, n)
    P(f"## 3. Validation set\nObserved 16/16 = 100% -> exact (Clopper-Pearson) 95% CI = [{lo:.3f}, {hi:.3f}].  "
      f"The val set could be hiding a true accuracy as low as {100*lo:.1f}%.\n")
    lo2, hi2 = clopper_pearson(int(round(0.984 * 624)), 624)
    P(f"Rohit's 98.4% on 624 test images = ~{624 - int(round(0.984*624))} errors; 95% CI [{lo2:.3f}, {hi2:.3f}] "
      f"(statistical noise only - leakage is on top of this).\n")
    open(RESULTS / "audit_summary.md", "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()